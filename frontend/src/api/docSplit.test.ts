import { describe, expect, it } from "vitest";
import {
  DOC_BODY_MARKER,
  docJoinHeadBody,
  docSplitHeadBody,
} from "./docSplit";

describe("docSplitHeadBody", () => {
  it("splits a document at the marker into its exact halves", () => {
    expect(
      docSplitHeadBody("head\n\n" + DOC_BODY_MARKER + "\n\nbody"),
    ).toEqual({ head: "head", body: "body", split: true });
  });

  it("splits a document stored with the Chinese marker of earlier seeds the same way", () => {
    expect(
      docSplitHeadBody(
        "head\n\n<!-- ↑唯讀區（程式產生，改不動）｜↓本體（可編輯，零變數） -->\n\nbody",
      ),
    ).toEqual({ head: "head", body: "body", split: true });
  });

  it("returns a markerless document whole and reports no split", () => {
    expect(docSplitHeadBody("head\nbody")).toEqual({
      head: "head\nbody",
      body: "",
      split: false,
    });
  });
});

describe("docJoinHeadBody", () => {
  it("joins the halves with the English marker", () => {
    expect(docJoinHeadBody("head", "body")).toBe(
      "head\n\n<!-- ↑ read-only (generated by the program, cannot be edited) | ↓ body (editable, no variables) -->\n\nbody",
    );
  });
});
